/**
 * Builds the three browser extensions from one shared source (extension-src/ + lib/ + data/):
 *
 *   npm run ext:build          # writes extension-chrome/, extension-firefox/, extension-edge/
 *   npm run ext:check          # rebuilds in memory and fails if any directory is out of date
 *
 * Each directory keeps its own hand-written manifest.json (browser-specific keys); everything
 * else in it is generated here. Output is bundled but not minified, so store reviewers can read it.
 */
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'extension-src');
export const TARGETS = ['extension-chrome', 'extension-firefox', 'extension-edge'];
const ENTRIES = { popup: 'src/popup.ts', app: 'src/app.ts', background: 'src/background.ts' };

/** Renders the site's React icon components to SVG strings (extension-src/icons-entry.tsx) in Node. */
export async function renderIcons() {
  const out = await build({
    entryPoints: [path.join(SRC, 'icons-entry.tsx')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    write: false,
    jsx: 'automatic',
    tsconfig: path.join(ROOT, 'tsconfig.json'),
    logLevel: 'warning',
    // Resolve React from the project; esbuild's ESM output needs require() for CJS deps.
    banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
    absWorkingDir: ROOT,
  });
  const tmp = path.join(ROOT, 'node_modules', '.cache', `w3l-icons-${process.pid}.mjs`);
  fs.mkdirSync(path.dirname(tmp), { recursive: true });
  fs.writeFileSync(tmp, out.outputFiles[0].contents);
  try {
    const mod = await import(`file://${tmp}`);
    return mod.renderIcons();
  } finally {
    fs.rmSync(tmp, { force: true });
  }
}

/** Every file under `dir`, as [relative path, absolute path]. */
function walkFiles(dir, rel = '') {
  return fs.readdirSync(path.join(dir, rel), { withFileTypes: true }).flatMap((e) => {
    const p = rel ? `${rel}/${e.name}` : e.name;
    return e.isDirectory() ? walkFiles(dir, p) : [[p, path.join(dir, p)]];
  });
}

export async function buildFiles() {
  /** @type {Record<string, Buffer>} */
  const files = {};
  const icons = await renderIcons();
  const result = await build({
    plugins: [
      {
        name: 'svg-icons',
        setup(b) {
          b.onResolve({ filter: /^virtual:svg-icons$/ }, () => ({ path: 'svg-icons', namespace: 'w3l' }));
          b.onLoad({ filter: /.*/, namespace: 'w3l' }, () => ({ contents: JSON.stringify(icons), loader: 'json' }));
        },
      },
    ],
    entryPoints: Object.fromEntries(Object.entries(ENTRIES).map(([k, v]) => [k, path.join(SRC, v)])),
    bundle: true,
    format: 'iife',
    target: ['chrome116', 'firefox128', 'edge116'],
    outdir: 'out',
    write: false,
    charset: 'utf8',
    legalComments: 'none',
    tsconfig: path.join(ROOT, 'tsconfig.json'),
    logLevel: 'warning',
    banner: { js: '/* Web3Lens extension. Generated by scripts/build-extensions.mjs from extension-src/ and lib/; do not edit. */' },
  });
  for (const f of result.outputFiles) files[path.basename(f.path)] = Buffer.from(f.contents);
  for (const [rel, abs] of walkFiles(path.join(SRC, 'static'))) files[rel] = fs.readFileSync(abs);
  for (const f of fs.readdirSync(path.join(SRC, 'icons'))) files[`icons/${f}`] = fs.readFileSync(path.join(SRC, 'icons', f));
  return files;
}

/** Generated files currently in a target directory (everything except manifest.json and *.md docs). */
export function existingFiles(dir) {
  const out = {};
  const walk = (rel) => {
    for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const p = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(p);
      else if (p !== 'manifest.json' && !p.endsWith('.md')) out[p] = fs.readFileSync(path.join(dir, p));
    }
  };
  if (fs.existsSync(dir)) walk('');
  return out;
}

async function main() {
  const check = process.argv.includes('--check');
  const files = await buildFiles();
  let stale = 0;
  for (const target of TARGETS) {
    const dir = path.join(ROOT, target);
    const have = existingFiles(dir);
    const names = new Set([...Object.keys(files), ...Object.keys(have)]);
    for (const name of names) {
      const want = files[name];
      if (!want) {
        if (check) {
          console.error(`${target}/${name}: not produced by the build (remove it)`);
          stale++;
        } else fs.rmSync(path.join(dir, name));
        continue;
      }
      if (have[name]?.equals(want)) continue;
      if (check) {
        console.error(`${target}/${name}: out of date`);
        stale++;
      } else {
        fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true });
        fs.writeFileSync(path.join(dir, name), want);
      }
    }
  }
  if (check && stale) {
    console.error(`\n${stale} file(s) out of date: run npm run ext:build`);
    process.exit(1);
  }
  const size = (n) => `${(files[n].length / 1024).toFixed(0)} KB`;
  console.log(`${check ? 'Up to date' : 'Built'}: ${TARGETS.join(', ')} (popup.js ${size('popup.js')}, app.js ${size('app.js')}, background.js ${size('background.js')})`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
