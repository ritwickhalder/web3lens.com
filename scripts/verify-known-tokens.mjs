const SYMBOL = '0x95d89b41';
const DECIMALS = '0x313ce567';

function decodeString(hex) {
  const b = Buffer.from(hex.slice(2), 'hex');
  if (b.length >= 64) {
    const len = Number(BigInt(`0x${b.subarray(32, 64).toString('hex')}`));
    if (len < 64) return b.subarray(64, 64 + len).toString('utf8');
  }
  return b.toString('utf8').replace(/\0+$/, '');
}

const out = { $comment: 'Well-known tokens whose balances are read live over RPC on chains without a free token index. Generated by scripts/verify-known-tokens.mjs; each entry was confirmed on-chain (symbol + decimals).', verifiedAt: new Date().toISOString(), chains: {} };
for (const [chain, { rpc, tokens }] of Object.entries(CANDIDATES)) {
  const body = tokens.flatMap(([a], i) => [
    { jsonrpc: '2.0', id: i * 2, method: 'eth_call', params: [{ to: a, data: SYMBOL }, 'latest'] },
    { jsonrpc: '2.0', id: i * 2 + 1, method: 'eth_call', params: [{ to: a, data: DECIMALS }, 'latest'] },
  ]);
  const res = await (await fetch(rpc, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })).json();
  const byId = new Map(res.map((r) => [r.id, r]));
  out.chains[chain] = [];
  tokens.forEach(([address, symbol, decimals], i) => {
    const s = byId.get(i * 2)?.result;
    const d = byId.get(i * 2 + 1)?.result;
    const gotSymbol = s && s !== '0x' ? decodeString(s) : null;
    const gotDecimals = d && d !== '0x' ? Number(BigInt(d)) : null;
    const ok = gotSymbol === symbol && gotDecimals === decimals;
    console.log(`${ok ? 'ok  ' : 'DROP'} ${chain} ${symbol} ${address} (on-chain: ${gotSymbol}, ${gotDecimals})`);
    if (ok) out.chains[chain].push({ address, symbol, decimals });
  });
}
fs.writeFileSync(path.join(ROOT, 'data', 'known-tokens.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log('Wrote data/known-tokens.json');
