import chainsJson from '@/data/chains.json';

/**
 * How a chain's search is handed off to an outside block explorer.
 * - `url`: open `url` with `{q}` replaced by the query
 * - `form`: submit a form with the query as `param` (some explorers only accept POST)
 * - `google`: no known explorer; search Google for `terms` plus the query
 */
export type Explorer =
  | { kind: 'url'; url: string }
  | { kind: 'form'; action: string; method: 'get' | 'post'; param: string }
  | { kind: 'google'; terms: string };

export type Chain = {
  id: string;
  name: string;
  /** The <option value> of the pre-Next.js site; kept for the parity test. */
  legacyValue: string;
  explorer: Explorer;
  /** The legacy site warned that this chain is "not yet supported" and used a substitute explorer. */
  fallback?: boolean;
};

/** Generated by scripts/convert-legacy-chains.mjs, in the legacy dropdown order. */
export const CHAINS = chainsJson as Chain[];

const BY_ID = new Map(CHAINS.map((c) => [c.id, c]));

export function getChain(id: string): Chain | undefined {
  return BY_ID.get(id);
}
